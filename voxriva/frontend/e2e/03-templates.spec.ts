import { expect, test } from "@playwright/test";
import { compose, createProject, createTemplate, editCode, setup, setVariables } from "./support/compose";

setup();

test("new templates are empty and email/push editing preserves scenarios, validation, and isolation", async ({ page }) => {
  const externalRequests: string[] = [];
  const origin = new URL(page.url()).origin;
  page.on("request", (request) => { if (request.url().startsWith("http") && new URL(request.url()).origin !== origin) externalRequests.push(request.url()); });
  await createProject(page, "Template studio");
  await createTemplate(page, "Welcome email");
  await expect(page.getByText("Start writing content to see a preview", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Save draft", exact: true })).toBeDisabled();
  await editCode(page, "Email subject", "Welcome, {{ name }}");
  await setVariables(page);
  await editCode(page, "Email HTML", '<h1>Hello {{ name }}!</h1><script>parent.hacked=true</script><img src="https://example.test/blocked.png"><a href="https://example.test/blocked">Link</a>');
  const email = page.frameLocator('iframe[title="Email HTML preview"]');
  await expect(email.getByRole("heading", { name: "Hello Taylor Synthetic!" })).toBeVisible();
  expect(await page.locator("iframe").getAttribute("sandbox")).toBe("");
  expect(await email.locator("script").count()).toBe(0);
  expect(await email.locator("a").getAttribute("href")).toBeNull();
  await editCode(page, "Email HTML", '<div style="font-family:system-ui;padding:24px"><h1>Hello {{ name }}!</h1><p>Your account is ready.</p></div>');
  await page.getByRole("tab", { name: "Test data", exact: true }).click();
  await page.getByLabel("Scenario name", { exact: true }).fill("Taylor");
  await page.getByRole("button", { name: "Save scenario", exact: true }).click();
  await editCode(page, "Fixture JSON", '{"name":42}');
  await expect(page.getByRole("region", { name: "Live preview" }).getByRole("alert").filter({ hasText: /context.name: Context violates type/ })).toBeVisible();
  await expect(page.getByRole("tabpanel", { name: "Test data", exact: true }).getByText(/Context violates type/)).toBeVisible();
  await expect(page.getByText("Unsaved changes", { exact: true })).toBeVisible();
  await editCode(page, "Fixture JSON", '{"name":"Taylor Synthetic"}');
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.getByText("Draft saved.", { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByText("Welcome, Taylor Synthetic", { exact: true })).toBeVisible();
  await page.screenshot({ path: test.info().outputPath("email-template.png"), fullPage: true, animations: "disabled" });
  await editCode(page, "Email subject", "{% if %}");
  await expect(page.getByRole("alert").filter({ hasText: /subject.1:|Subject, line 1:/ }).first()).toBeVisible();
  await editCode(page, "Email subject", "Hello {{ name }}");
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.getByText("Draft saved.", { exact: true })).toBeVisible();
  await createTemplate(page, "Welcome push", true);
  await expect(page.getByText("Start writing content to see a preview", { exact: true })).toBeVisible();
  await setVariables(page);
  await editCode(page, "Push title", "Ready, {{ name }}");
  await editCode(page, "Push body", "Your account is ready.");
  await editCode(page, "Push data", '{"route":"/welcome/{{ name }}"}');
  await expect(page.getByRole("heading", { name: "Ready, Taylor Synthetic" })).toBeVisible();
  await page.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(page.getByText("Draft saved.", { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("heading", { name: "Ready, Taylor Synthetic" })).toBeVisible();
  await page.screenshot({ path: test.info().outputPath("push-template.png"), fullPage: true, animations: "disabled" });
  expect(externalRequests).toEqual([]);
});

