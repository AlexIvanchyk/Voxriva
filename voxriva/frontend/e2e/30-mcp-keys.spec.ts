import { expect, test } from "@playwright/test";
import { nav, signIn } from "./support/compose";

test("API keys unifies delivery and owned MCP keys without expanding editor or viewer permissions", async ({ page }, info) => {
  test.skip(!process.env.VOXRIVA_TEST_PROJECT?.startsWith("voxriva-test-mcp-keys-"), "Run scripts/test-mcp-keys-browser.sh for its isolated stack");
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto("/");
  await signIn(page, process.env.VOXRIVA_TEST_EMAIL!, process.env.VOXRIVA_TEST_PASSWORD!);
  const csrf = { "X-CSRF-Token": (await (await page.request.get("/api/v1/auth/session")).json()).csrf_token };
  async function post(path: string, data: object) { const response = await page.request.post(`/api/v1${path}`, { headers: csrf, data }); expect(response.ok(), await response.text()).toBeTruthy(); return response.json(); }
  const editable = await post("/projects", { name: "Fictional Studio" });
  const readable = await post("/projects", { name: "Fictional Library" });
  const env = await post(`/projects/${editable.id}/environments`, { name: "Development" });
  await post("/members", { email: "mcp-editor@example.test", display_name: "Synthetic Editor", password: "Synthetic editor password", projects: [{ project_id: editable.id, role: "template_editor" }, { project_id: readable.id, role: "viewer" }] });
  await post("/members", { email: "mcp-viewer@example.test", display_name: "Synthetic Viewer", password: "Synthetic viewer password", projects: [{ project_id: editable.id, role: "viewer" }] });
  await page.goto(`/api-keys?project=${editable.id}&environment=${env.id}`);
  await page.getByRole("button", { name: "Create API key" }).click();
  let dialog = page.getByRole("dialog", { name: "Create API key" });
  await dialog.getByLabel("Name", { exact: true }).fill("Fictional delivery key");
  await dialog.getByRole("button", { name: "Create key", exact: true }).click();
  let secretDialog = page.getByRole("dialog", { name: "Copy your API key" });
  await expect(secretDialog.locator(".issued-key")).toContainText("vxk_");
  await secretDialog.getByRole("button", { name: "Integration examples" }).click();
  await expect(page.getByRole("dialog", { name: "Integration examples" })).toContainText("Python");
  await page.getByRole("dialog", { name: "Integration examples" }).getByRole("button", { name: "Close", exact: true }).click();
  await expect(secretDialog.locator(".issued-key")).toContainText("vxk_");
  await secretDialog.getByRole("button", { name: "Done", exact: true }).click();
  await page.getByRole("button", { name: "Create API key" }).click();
  dialog = page.getByRole("dialog", { name: "Create API key" });
  await dialog.getByRole("combobox", { name: "Purpose", exact: true }).press("ArrowDown");
  await page.locator(".ant-select-dropdown:visible").getByText("Template / MCP", { exact: true }).click();
  await expect(page.locator(".ant-select-dropdown:visible")).toHaveCount(0);
  await dialog.getByLabel("Name", { exact: true }).fill("Fictional MCP key");
  await dialog.getByRole("button", { name: "Select all currently available projects" }).click();
  await dialog.getByRole("combobox", { name: "Template permissions", exact: true }).press("ArrowDown");
  await page.locator(".ant-select-dropdown:visible").getByText("Read and write templates", { exact: true }).click();
  await expect(page.locator(".ant-select-dropdown:visible")).toHaveCount(0);
  await dialog.getByRole("heading", { name: "Create API key" }).click();
  await expect(page.locator(".ant-select-dropdown:visible")).toHaveCount(0);
  await page.screenshot({ path: info.outputPath("mcp-create.png"), fullPage: true, animations: "disabled" });
  await dialog.getByRole("button", { name: "Create key", exact: true }).click();
  secretDialog = page.getByRole("dialog", { name: "Copy your API key" });
  const token = await secretDialog.locator(".issued-key").innerText();
  expect(token).toContain("vxm_");
  await page.context().grantPermissions(["clipboard-read", "clipboard-write"]);
  await secretDialog.locator(".issued-key").getByRole("button", { name: "Copy", exact: true }).click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(token.trim());
  await secretDialog.getByRole("button", { name: "Connection instructions" }).click();
  await expect(secretDialog.getByText("Streamable HTTP with a management bearer token")).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(secretDialog.locator(".issued-key")).toContainText("vxm_");
  await expect(secretDialog.getByLabel("MCP server URL")).toBeVisible();
  await secretDialog.getByRole("button", { name: "Done", exact: true }).click();
  await expect(page.getByText(token, { exact: true })).toHaveCount(0);
  const mcpRow = page.getByRole("row").filter({ hasText: "Fictional MCP key" });
  await expect(mcpRow).toContainText("Read / write templates");
  await expect(mcpRow).toContainText("Fictional Studio");
  await expect(mcpRow).toContainText("Fictional Library");
  await expect(page.getByRole("row").filter({ hasText: "Fictional delivery key" })).toContainText("Environment delivery");
  await mcpRow.getByRole("button", { name: "Connect", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "MCP connection instructions" })).not.toContainText(token);
  await page.getByRole("dialog").getByRole("button", { name: "Done", exact: true }).click();
  await mcpRow.getByRole("button", { name: "Revoke", exact: true }).click();
  await page.getByRole("button", { name: "Confirm", exact: true }).click();
  await expect(mcpRow).toContainText("Revoked");
  await page.screenshot({ path: info.outputPath("mcp-key-inventory.png"), fullPage: true, animations: "disabled" });
  await page.getByRole("button", { name: "Sign out", exact: true }).click();
  await signIn(page, "mcp-editor@example.test", "Synthetic editor password");
  await nav(page, "API keys").click();
  await expect(page.getByText("Fictional delivery key", { exact: true })).toHaveCount(0);
  await expect(page.getByText("Fictional MCP key", { exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Create API key" }).click();
  dialog = page.getByRole("dialog", { name: "Create API key" });
  await expect(dialog.getByRole("combobox", { name: "Environment", exact: true })).toHaveCount(0);
  await dialog.getByRole("combobox", { name: "Template permissions", exact: true }).press("ArrowDown");
  await page.locator(".ant-select-dropdown:visible").getByText("Read and write templates", { exact: true }).click();
  await expect(page.locator(".ant-select-dropdown:visible")).toHaveCount(0);
  await dialog.getByRole("combobox", { name: "Allowed projects", exact: true }).press("ArrowDown");
  await expect(page.locator(".ant-select-dropdown:visible").getByText("Fictional Library", { exact: true }).locator("..")).toHaveClass(/ant-select-item-option-disabled/);
  await page.keyboard.press("Escape");
  await dialog.getByRole("button", { name: "Select all currently available projects" }).click();
  await dialog.getByLabel("Name", { exact: true }).fill("Editor authoring key");
  await dialog.getByRole("button", { name: "Create key", exact: true }).click();
  await page.getByRole("dialog", { name: "Copy your API key" }).getByRole("button", { name: "Done", exact: true }).click();
  const editorRow = page.getByRole("row").filter({ hasText: "Editor authoring key" });
  await expect(editorRow).toContainText("Read / write templates");
  await expect(editorRow).not.toContainText("Fictional Library");
  await page.getByRole("button", { name: "Sign out", exact: true }).click();
  await signIn(page, "mcp-viewer@example.test", "Synthetic viewer password");
  await nav(page, "API keys").click();
  await page.getByRole("button", { name: "Create API key" }).click();
  dialog = page.getByRole("dialog", { name: "Create API key" });
  await dialog.getByLabel("Name", { exact: true }).fill("Viewer read key");
  await dialog.getByRole("button", { name: "Select all currently available projects" }).click();
  await dialog.getByRole("button", { name: "Create key", exact: true }).click();
  await page.getByRole("dialog", { name: "Copy your API key" }).getByRole("button", { name: "Done", exact: true }).click();
  await expect(page.getByRole("row").filter({ hasText: "Viewer read key" })).toContainText("Read-only templates");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "Create API key" }).click();
  dialog = page.getByRole("dialog", { name: "Create API key" });
  await dialog.getByRole("spinbutton", { name: "Expires in days" }).scrollIntoViewIfNeeded();
  await expect(dialog.getByRole("button", { name: "Create key", exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await expect(dialog).toHaveCSS("transform", "none");
  await page.screenshot({ path: info.outputPath("mcp-mobile-create.png"), fullPage: true, animations: "disabled" });
  await dialog.getByLabel("Name", { exact: true }).fill("Mobile viewer key");
  await dialog.getByRole("button", { name: "Select all currently available projects" }).click();
  await dialog.getByRole("button", { name: "Create key", exact: true }).click();
  secretDialog = page.getByRole("dialog", { name: "Copy your API key" });
  await secretDialog.getByRole("button", { name: "Connection instructions" }).click();
  await expect(secretDialog.getByRole("button", { name: "Done", exact: true })).toBeVisible();
  await secretDialog.locator(".issued-key").scrollIntoViewIfNeeded();
  await expect(secretDialog.locator(".issued-key")).toContainText("vxm_");
  await secretDialog.getByRole("button", { name: "Done", exact: true }).click();
});
