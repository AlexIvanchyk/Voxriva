  await dialog.getByLabel("Name", { exact: true }).fill("production");
  await dialog.getByLabel("Project", { exact: true }).fill("Commerce");
  await page.locator(".ant-select-dropdown:visible").getByText("Commerce", { exact: true }).click();
  await expect(dialog).toHaveCSS("transform", "none");
  await page.screenshot({ path: test.info().outputPath("create-environment.png"), fullPage: true, animations: "disabled" });
  await dialog.getByRole("button", { name: "Create environment", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await nav(page, "API keys").click();
  await page.getByRole("button", { name: "Create API key", exact: true }).click();
  dialog = page.getByRole("dialog");
  await dialog.getByLabel("Name", { exact: true }).fill("Checkout integration");
  await dialog.getByRole("button", { name: "Create key", exact: true }).click();
  const secret = page.getByText(/^vxk_[A-Za-z0-9_-]{43}$/);
  await expect(secret).toBeVisible();
