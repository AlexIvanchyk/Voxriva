test("edits a member name and project roles without changing email", async ({ page }) => {
  const headers = { "X-CSRF-Token": (await (await page.request.get("/api/v1/auth/session")).json()).csrf_token };
  const projects = [];
  for (const name of ["Edit North", "Edit South", "Edit West"]) projects.push(await (await page.request.post("/api/v1/projects", { headers, data: { name } })).json());
  const item = await (await page.request.post("/api/v1/members", { headers, data: { email: "editable.demo@example.test", display_name: "Editable Demo", password: "Synthetic edit password", projects: projects.slice(0, 2).map((project) => ({ project_id: project.id, role: "viewer" })) } })).json();
  await page.goto(`/members?project=${projects[0].id}`);
  const row = page.getByRole("row").filter({ hasText: "editable.demo@example.test" });
  await row.getByRole("button", { name: "Edit member", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog.getByLabel("Email address", { exact: true })).toBeDisabled();
  await expect(dialog.getByLabel("Email address", { exact: true })).toHaveValue("editable.demo@example.test");
  await dialog.getByLabel("Full name", { exact: true }).fill("Updated Demo");
  await dialog.getByLabel("Project role", { exact: true }).press("ArrowDown");
  await page.locator(".ant-select-dropdown:visible").getByText("Operator", { exact: true }).click();
  await dialog.getByRole("button", { name: "Remove project", exact: true }).nth(1).click();
  await dialog.getByRole("button", { name: "Add another project", exact: true }).click();
  await dialog.getByLabel("Project 2", { exact: true }).fill("Edit West");
  await page.locator(".ant-select-dropdown:visible").getByText("Edit West", { exact: true }).click();
  await expect(page.locator(".ant-select-dropdown:visible")).toHaveCount(0);
  await dialog.getByLabel("Project role 2", { exact: true }).press("ArrowDown");
  await expect(page.locator(".ant-select-dropdown:visible")).toHaveCSS("transform", "none");
  await page.locator(".ant-select-dropdown:visible").getByText("Template editor", { exact: true }).click();
  await dialog.getByRole("button", { name: "Save member", exact: true }).click(); await expect(dialog).toHaveCount(0);
  await expect(row.getByText("Updated Demo", { exact: true })).toBeVisible();
  const updated = (await (await page.request.get("/api/v1/members")).json()).find((member: { account_id: string }) => member.account_id === item.account_id);
  expect(updated.email).toBe("editable.demo@example.test"); expect(updated.display_name).toBe("Updated Demo");
  expect(updated.projects.map((grant: { project_id: string; role: string }) => [grant.project_id, grant.role]).sort()).toEqual([[projects[0].id, "operator"], [projects[2].id, "template_editor"]].sort());
});
